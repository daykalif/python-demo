"""
一、什么是正则表达式，有什么用？
正则表达式定义了字符串的组成规则，我们可以依据这套规则，从文本里匹配、提取或者替换符合格式要求的字符串，常用来做手机号筛选、邮箱提取、内容过滤、格式校验这类文本处理工作。

二、字符串前的 r 标识是什么意思？
r代表原始字符串，它会让字符串里原本 Python 语法里的转义字符（比如\n、\d里的反斜杠）失去转义效果，反斜杠会作为普通字符保留，避免正则里的\被 Python 提前解析破坏规则，让正则表达式写法更稳定。

三、re 模块三个函数的作用与区别:
1. match(正则表达式, 文本字符串)
作用：只从文本字符串的开头位置进行匹配，开头不符合规则就直接匹配失败，不会向后继续检索。
返回：匹配成功返回 Match 对象，失败返回None。

2. search(正则表达式, 文本字符串)
作用：扫描整个文本字符串，找到第一个符合正则规则的匹配项就停止检索。
返回：匹配成功返回 Match 对象，失败返回None。

3. findall(正则表达式, 文本字符串)
作用：扫描整个文本字符串，找出所有符合正则规则的匹配项。
返回：把所有匹配到的内容以列表形式返回，没有匹配项则返回空列表。
"""
import re

# s1：字符串**开头**就是手机号
s1 = "18809090000是我的手机号，你记住了吗？我的另一个手机号是18800008888，两个QQ号分别是155998992 和 18809091293821 你记住了吗?"
# s2：手机号在字符串中间，开头是中文
s2 = "我的手机号是18809090000，你记住了吗？我的另一个手机号是18800008888，两个QQ号分别是155998992 和 18809091293821 你记住了吗?"

# 手机号正则规则：1开头 + 3-9第二位数字 + 9位数字，合计11位手机号
phone_pattern = r"1[3-9]\d{9}"

# match - 从字符串的开头开始匹配（匹配第一个匹配项） ---> Match 对象
# 对s1：开头就是手机号，匹配成功
result = re.match(phone_pattern, s1)
print(result.group())  # 获取匹配到的完整字符串：18809090000
print(result.span())  # 获取匹配起止索引：(0, 11)
print(result.start())  # 起始索引：0
print(result.end())  # 结束索引：11

# 对s2：开头是中文，不是手机号，匹配失败，调用group()会报错
result2 = re.match(phone_pattern, s2)
print(result2)  # 输出 None

# search - 从任意为止开始，搜索第一个匹配项） ---> Match 对象
result = re.search(phone_pattern, s1)
print(result.group())  # 获取匹配到的完整字符串：18809090000
print(result.span())  # 获取匹配起止索引：(0, 11)
print(result.start())  # 起始索引：0
print(result.end())  # 结束索引：11

# findall - 从任意位置开始，搜索所有匹配项  ---> List
result = re.findall(phone_pattern, s1)
print(result)

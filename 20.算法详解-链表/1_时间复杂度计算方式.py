# 题目：如果 a+b+c=1000，且 a^2+b^2=c^2（a,b,c 为自然数），如何求出所有 a、b、c 可能的组合？
"""
1. 严格意义上的时间复杂度（大O表示法）
由于循环范围是固定的常量 1001（不依赖任何外部输入变量 n），程序总执行次数恒定为：
1001 × 1001 × 1001 ≈ 10.03 亿次

无论运行多少次，这个次数都不变，所以严格的时间复杂度是 O(1)（常数时间）。

2. 算法竞赛/面试视角（推荐这么看）
如果你把题目中的 1000 看作待求解的变量 n（即 a+b+c = n），那么这段代码就是暴力枚举，时间复杂度为 O(n³)。

方式一到方式三的转变：
    时间复杂度（若把1000看作变量 n）：从 O(n³) 降为 O(n²)。
"""

# 方式一：（5分多钟）1001 * 1001 * 1001 * 10（步）
for a in range(0, 1001):
    for b in range(0, 1001):
        for c in range(0, 1001):
            if a ** 2 + b ** 2 == c ** 2 and a + b + c == 1000:
                print("a,b,c:%d,%d,%d" % (a, b, c))

# 方式二：（2秒多） 1001 * 1001 * 10（步）
for a in range(0, 1001):
    for b in range(0, 1001):
        c = 1000 - a - b
        if a ** 2 + b ** 2 == c ** 2:
            print("a,b,c:%d,%d,%d" % (a, b, c))

# 方式三：（0.3秒多）
for a in range(0, 1001):
    for b in range(0, 1001):
        c = 1000 - a - b
        if a ** 2 + b ** 2 == c ** 2:
            print("a, b, c: %d, %d, %d" % (a, b, c))


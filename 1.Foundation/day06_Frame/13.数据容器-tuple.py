# 案例1: 现有两个变量, 分别为: a = 10, b = 20, 现需要将这两个变量值交换, 然后输出到控制台。
a = 10
b = 20

# 利用元组组包与解包实现变量交换
a, b = b, a

print(a)  # 20
print(b)  # 10

# 案例2: 现有三个变量，分别为：a = 100，b = 200，c = 300，现需要将这三个变量值进行交换，将 a,b,c 的原值分别赋值给 c,a,b，并将结果输出到控制台。
a = 100
b = 200
c = 300

# 右侧a,b,c先组包成元组(100,200,300)，再解包依次赋值给左侧c,a,b
c, a, b = a, b, c

print(a)
print(b)
print(c)

# -----------------------------------学生成绩单需求文案 案例----------------------------------------------------------------------
"""
需求说明:

根据提供的学生成绩单，完成以下 3 项任务：
计算每个学生的总分、各科平均分，然后一并输出出来。
统计各科成绩的最低分、最高分、平均分，并输出。
查找成绩优秀（平均分大于 90）的学生，并输出。
"""

# 定义学生成绩单（元组类型）
students = (
    ("S001", "王林", 85, 92, 78),
    ("S002", "李慕婉", 92, 88, 95),
    ("S003", "十三", 78, 85, 82),
    ("S004", "曾牛", 88, 79, 91),
    ("S005", "周轶", 95, 96, 89),
    ("S006", "王卓", 76, 82, 77),
    ("S007", "红蝶", 89, 91, 94),
    ("S008", "徐立国", 75, 69, 82),
    ("S009", "许木", 86, 89, 98),
    ("S010", "遁天", 66, 59, 72)
)

subjects = ["语文", "数学", "英语"]  # 对应第3、4、5个元素

# ---------------------- 需求1：计算每个学生的总分、平均分 ----------------------
print("===== 学生个人成绩统计 =====")
for stu in students:
    stu_id, name, chinese, math, english = stu
    total = chinese + math + english
    avg = total / 3
    print(f"学号：{stu_id} | 姓名：{name} | 总分：{total} | 平均分：{avg:.2f}")

# ---------------------- 需求2：统计各科的最低分、最高分、平均分 ----------------------
print("\n===== 各科整体成绩统计 =====")
# 提取各科所有成绩
chinese_scores = [s[2] for s in students]
print(chinese_scores)  # [85, 92, 78, 88, 95, 76, 89, 75, 86, 66]

math_scores = [s[3] for s in students]
english_scores = [s[4] for s in students]

subject_scores = [chinese_scores, math_scores, english_scores]
for sub_name, scores in zip(subjects, subject_scores):
    min_s = min(scores)
    max_s = max(scores)
    avg_s = sum(scores) / len(scores)
    print(f"{sub_name} | 最低分：{min_s} | 最高分：{max_s} | 平均分：{avg_s:.2f}")

# ---------------------- 需求3：查找平均分>90的优秀学生 ----------------------
print("\n===== 成绩优秀学生（平均分>90） =====")
excellent_stus = []
for stu in students:
    stu_id, name, chinese, math, english = stu
    total = chinese + math + english
    avg = total / 3
    if avg > 90:
        excellent_stus.append((stu_id, name, avg))

if excellent_stus:
    for stu_id, name, avg in excellent_stus:
        print(f"学号：{stu_id} | 姓名：{name} | 平均分：{avg:.2f}")
else:
    print("暂无平均分大于90的优秀学生")

"""
元组 - 组包与解包

一、核心概念
组包（Packing）：将多个值合并到一个容器（元组、列表）中。
解包（Unpacking）：将容器（元组、列表）解开成独立的元素，分别赋值给多个变量。
"""

# 定义元组，组包
t1 = (5, 7, 9, 1)
# 定义元组，组包（省略括号写法）
t2 = 5, 7, 9, 1

# 基础解包
a, b, c, d = t1

# (*)扩展解包
x, *y, z = t2  # x为5, y为[7, 9], z为1
s, *o = t2  # s为5, o为[7, 9, 1]
*o, e = t2  # o为[5, 7, 9], e为1
print(o)
print(e)


"""
列表有什么特点？
- 元素可重复、有序、可以修改的

如果要记录一些信息，而这些信息，不能被修改，只能查询呢？
- 列表就不适合了
- 此时就可以考虑使用元组，元组与列表最大的不同点在于：元组一旦定义完成，不可修改


一、元组介绍
- 元组是不可变的序列，结构类似于列表，但创建之后内部内容就不能直接修改。

二、元组特点
- 可以存储不同数据类型的元素
- 元素允许重复、整体有序、不可以修改，支持通过索引访问元素、支持切片操作
"""

"""
# 定义普通元组
元组名称 = (元素1, 元素2, ...)

# 定义空元组两种写法
元组名称 = ()
元组名称 = tuple()
"""

# 定义普通元组
t1 = (5, 7, 9, 1, 2, 3, 10, 6, 4, 8, 12, 7, 5)
print(t1)
print(type(t1))

# 索引访问
print(t1[0])
print(t1[-1])

# t1[1] = 0  # 报错，元祖不可修改

# 定义空元组
t2 = ()
print(t2)
print(type(t2))  # tuple类型

t3 = tuple()

# 注意点：如果定义单元素的元祖，单个元素之后需要加上逗号，比如(100,)
t4 = (100)
print(t4)
print(type(t4))  # int类型

# 切片
print(t1[0:5:1])

# count() 统计某个元素的个数
print(t1.count(5))

# index() 获取某个元素的索引(第一个元素的位置)
print(t1.index(8))

"""
元组-小结
1. 元组的特点
- 元素可以重复存放
- 元素是有序排列的，可以通过索引定位元素
- 属于不可变序列，创建后不能直接修改元素内容（只读特性）

2. 元组的两个查询方法
- count(目标元素)：统计目标元素在元组中出现的次数
- index(目标元素)：获取目标元素第一次出现的索引位置，若元素不存在会抛出ValueError报错

3. 元组使用注意事项
- 定义单个元素的元组时，必须在元素末尾添加逗号，否则 Python 会把括号识别为普通括号，变量不会被判定为元组：
- 正确写法：('A', )，类型为元组
- 错误写法：('A')，仅代表字符串'A'本身，不是元组
"""


"""
循环嵌套：根据输入的长方形的长度 m，宽度 n，打印一个长方形；
如下：是一个长度为 10，宽度为 5 的长方形
* * * * * * * * * *
* * * * * * * * * *
* * * * * * * * * *
* * * * * * * * * *
* * * * * * * * * *

关键知识点
print("*")：自带换行效果，每一次执行都会输出到新的一行。
print("*", end=" ")：end 参数表示每次输出的结尾字符，默认是 \n（换行），这里设置为空格，使星号在同一行横向排列。
"""

# 1. 接收键盘录入 m ，n
# 长度
m = int(input("请输入长方形的长度："))
# 宽度
n = int(input("请输入长方形的宽度："))

# 2. 打印长方形
for j in range(n):  # 控制行
    for i in range(m):  # 控制列
        print("*", end=" ")
    print()


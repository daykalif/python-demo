"""
计算1-100之间所有偶数的累加之和
"""
total = 0  # 记录累加之和
i = 1  # 循环开始数字

while i <= 100:
    if i % 2 == 0:
        total += i
    i += 1
print(f"1-100之间的偶数累加之和：{total}")

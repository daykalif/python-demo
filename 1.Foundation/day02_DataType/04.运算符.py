# 案例1：键盘输入一个整数，判断这个数字是否在 10-20 之间 --> 在: True，不在: False
n = int(input("请输入一个整数："))

# 写法1：使用 and 连接两个条件
print(f"{n}在10-20之间：", n >= 10 and n <= 20)

# 写法2：Python 连续比较写法（等价于写法1）
print(f"{n}在10-20之间：", 10 <= n <= 20)






# 案例2：键盘输入一个整数，判断这个数字是否不在10-20之间
n = int(input("请输入一个整数："))

# 使用 or 连接两个条件，满足其一则为 True
print(f"{n}不在10-20之间：", n < 10 or n > 20)
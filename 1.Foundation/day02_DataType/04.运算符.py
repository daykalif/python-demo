# 算术运算符：+  -  *  /  //  %  **
print("10 + 4 = ", 10 + 4)  # 加
print("10 - 4 = ", 10 - 4)  # 减
print("10 * 4 = ", 10 * 4)  # 乘
print("10 / 4 = ", 10 / 4)  # 除 - 2.5
print("10 // 4 = ", 10 // 4) # 整除(结果为整数) - 2
print("10 % 4 = ", 10 % 4)  # 取余/求模 - 2
print("10 ** 4 = ", 10 ** 4)# 幂指数，10的4次方 - 10000

# 算术运算符的优先级 --> ** --> * / // % --> + -
print("0.1 + 10 / 4**2 = ", 0.1 + 10 / 4 ** 2)





# 案例：输入两个数 x 和 y ，计算 x + y 以及 x - y 的结果并输出
# float(,,,) ---> 将其他类型转为浮点数类型
x = float(input("请输入x的值："))
y = float(input("请输入y的值："))

print("x + y = ", x + y)    # x + y =  0.9
print("x - y = ", x - y)    # x - y =  0.09999999999999998      # 注意：计算机底层是基于二进制来进行数据的存储和处理的，而二进制无法精确表示所有的小数，因此在对小数进行存储和处理的过程中就会存在一定的精度丢失问题。




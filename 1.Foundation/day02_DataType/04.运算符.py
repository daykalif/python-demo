# 比较运算符：==  !=  >  >=  <  <=
print("100 == 100 吗 : ", 100 == 100)      # True
print("'100' == '100' 吗 : ", "100" == "100")  # True
print("100 != 100 吗 : ", 100 != 100)      # False

print("100 < 100 吗 : ", 100 < 100)        # False
print("100 <= 100 吗 : ", 100 <= 100)      # True

print("100 > 100 吗 : ", 100 > 100)        # False
print("100 >= 100 吗 : ", 100 >= 100)      # True



